/*
 * mcp2515.h — минимальный драйвер CAN-контроллера MCP2515 для ATtiny85.
 *
 * Реализовано только то, что нужно устройству измерения батареи:
 *   - инициализация на скорости 500 кбит/с;
 *   - передача стандартных (11-битный ID) фреймов до 8 байт;
 *   - чтение счётчиков ошибок (диагностика, байт состояния).
 * Приём не используется: устройство только публикует данные в шину.
 */
#ifndef MCP2515_H
#define MCP2515_H

#include <Arduino.h>

// Частота кварца на модуле MCP2515, МГц. Большинство синих модулей — 8 МГц,
// встречаются 16 МГц (смотри маркировку кварца). От этого зависит CNF1.
#define MCP2515_CRYSTAL_MHZ 8

// Инициализация: сброс, настройка битового тайминга, нормальный режим.
// Возвращает true, если контроллер отвечает и перешёл в нормальный режим.
bool mcp2515_init();

// Отправка фрейма. id — 11-битный идентификатор, len <= 8.
// Возвращает true, если фрейм принят контроллером и передан в шину
// (флаг TXREQ снялся — т.е. сообщение ушло и было подтверждено ACK).
bool mcp2515_send(uint16_t id, const uint8_t *data, uint8_t len);

// Диагностика: счётчики ошибок передачи/приёма и флаги EFLG.
void mcp2515_read_errors(uint8_t *tec, uint8_t *rec, uint8_t *eflg);

#endif
